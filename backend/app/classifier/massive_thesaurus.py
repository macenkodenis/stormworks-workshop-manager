# Merge massive terms into DOMAIN_THESAURUS for full coverage
def get_thesaurus_matches(word: str) -> list:
    cleaned = word.strip().lower().replace("-", " ").replace("_", " ")
    results = []
    
    # Direct match or exact alias lookup
    normalized_keys = {
        k.replace("_", " "): k for k in MASSIVE_VEHICLE_DATABASE.keys()
    }
    
    # 1. Exact match (e.g. "tank", "helicopter", "armored vehicle", "offroad truck")
    if cleaned in MASSIVE_VEHICLE_DATABASE:
        results.extend(MASSIVE_VEHICLE_DATABASE[cleaned])
    elif cleaned in normalized_keys:
        results.extend(MASSIVE_VEHICLE_DATABASE[normalized_keys[cleaned]])
        
    # 2. Category word matching (e.g. "truck" matches "truck", "offroad_truck", but only for significant length)
    for norm_name, orig_key in normalized_keys.items():
        if orig_key == cleaned or norm_name == cleaned:
            continue
        # If the query matches a discrete word in category name or vice versa
        if len(cleaned) >= 4 and (cleaned in norm_name or norm_name in cleaned):
            for m in MASSIVE_VEHICLE_DATABASE[orig_key]:
                if m not in results:
                    results.append(m)
                    
    return results
